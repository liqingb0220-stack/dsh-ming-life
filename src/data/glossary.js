export const termOf = k => GLOSSARY[k] || null;

/** 从一段文字里找出出现过的术语（长词优先，避免「正官」被「官」截断） */
const KEYS = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);
export function findTerms(text) {
  if (!text) return [];
  const found = [];
  KEYS.forEach(k => {
    if (text.includes(k) && !found.some(f => f.includes(k))) found.push(k);
  });
  return found;
}
